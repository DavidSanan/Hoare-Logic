#!/usr/bin/env python3
"""Collect every exercise file (exercises/*.hl) into exercises/bundle.js.

The website loads bundle.js with a <script> tag. A page opened directly from
the disk cannot read the .hl files itself, so they are bundled.

Usage, from the folder "website":
    python3 tools/build_exercises.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXERCISES = ROOT / "exercises"


def main():
    files = sorted(EXERCISES.glob("*.hl"))
    entries = [{"file": f.name, "text": f.read_text(encoding="utf-8")} for f in files]
    out = EXERCISES / "bundle.js"
    body = json.dumps(entries, ensure_ascii=False, indent=1)
    out.write_text(
        "// Generated by tools/build_exercises.py from the .hl files of this folder.\n"
        "// Do not edit by hand: edit the .hl files and run the script again.\n"
        "window.HL_EXERCISE_SOURCES = " + body + ";\n",
        encoding="utf-8",
    )
    print("Wrote %s with %d exercise(s)." % (out.relative_to(ROOT), len(entries)))


if __name__ == "__main__":
    main()
